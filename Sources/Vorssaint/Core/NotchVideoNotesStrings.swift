    let back: String
    let backward: String
    let forward: String
    let playPause: String
    let playFromFormat: String
    let showInSafari: String
    let saved: String
    let waiting: String
    let noKey: String
    let rejected: String
    let settingsHint: String
    let address: String
    let apiKey: String
    let saveKey: String
    let removeKey: String
    let keySaved: String
    let javaScriptHint: String
    let invalidAddress: String

    func count(_ count: Int, agreement: CountAgreement) -> String {
        let format: String
        switch agreement {
        case .oneAndMany:
            format = count == 1 ? noteOne : noteMany
        case .byLastDigits:
            let last = count % 10, lastTwo = count % 100
            format = last == 1 && lastTwo != 11 ? noteOne
                : (2...4).contains(last) && !(12...14).contains(lastTwo) ? noteFew : noteMany
        case .byWholeNumber:
            format = count == 1 ? noteOne : (2...4).contains(count) ? noteFew : noteMany
        }
        return String(format: format, count)
    }

    func playFrom(_ time: String) -> String { String(format: playFromFormat, time) }
}

